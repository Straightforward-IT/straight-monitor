SELECT
  tp.ID,
  tp.IPERSONALNR,
  tp.ID_LCS_TARIF,
  tp.ID_LCS_TARIFMAGRUPPE,
  tp.ID_LCS_TARIFGRUPPEN,
  tp.ID_LCS_TARIFSTUFEN,
  tp.DTVON,
  tp.DTBIS
FROM LCS_TARIFPERSONAL tp
JOIN PERSONAL p
  ON p.PERSONALNR = tp.IPERSONALNR
WHERE
  (
    tp.DTBIS IS NULL
    OR tp.DTBIS >= DATE '2026-01-01'
  )
  AND p.PERSSTATUS IN (1, 2)
ORDER BY
  tp.IPERSONALNR,
  tp.DTVON;
